# usbdesc.py - генератор fpga/rtl/usb_desc_rom.sv: ПЗУ описателей USB (клавиатура boot + абсолютная мышь).
# Запуск: python scripts/usbdesc.py (нужен только при изменении описателей; результат хранится в версиях).
# VID/PID 1209:0001 - тестовый идентификатор для разработки.
import os
VID, PID, BCD = 0x1209, 0x0001, 0x0100
def w16(v): return [v & 0xFF, v >> 8]
def s(txt):
    b = [2 + 2*len(txt), 3]
    for ch in txt: b += w16(ord(ch))
    return b
kbd_rpt = [0x05,0x01, 0x09,0x06, 0xA1,0x01,
    0x05,0x07, 0x19,0xE0, 0x29,0xE7, 0x15,0x00, 0x25,0x01, 0x75,0x01, 0x95,0x08, 0x81,0x02,   # модификаторы
    0x95,0x01, 0x75,0x08, 0x81,0x01,                                                           # резерв
    0x95,0x05, 0x75,0x01, 0x05,0x08, 0x19,0x01, 0x29,0x05, 0x91,0x02,                          # 5 светодиодов
    0x95,0x01, 0x75,0x03, 0x91,0x01,
    0x95,0x06, 0x75,0x08, 0x15,0x00, 0x26,0xFF,0x00, 0x05,0x07, 0x19,0x00, 0x2A,0xFF,0x00, 0x81,0x00,  # 6 клавиш
    0xC0]
mouse_rpt = [0x05,0x01, 0x09,0x02, 0xA1,0x01, 0x09,0x01, 0xA1,0x00,
    0x05,0x09, 0x19,0x01, 0x29,0x05, 0x15,0x00, 0x25,0x01, 0x95,0x05, 0x75,0x01, 0x81,0x02,     # 5 кнопок
    0x95,0x01, 0x75,0x03, 0x81,0x01,
    0x05,0x01, 0x09,0x30, 0x09,0x31, 0x15,0x00, 0x26,0xFF,0x7F, 0x75,0x10, 0x95,0x02, 0x81,0x02,  # X, Y 0..32767 абсолютные
    0x09,0x38, 0x15,0x81, 0x25,0x7F, 0x75,0x08, 0x95,0x01, 0x81,0x06,                           # колесо
    0x05,0x0C, 0x0A,0x38,0x02, 0x15,0x81, 0x25,0x7F, 0x75,0x08, 0x95,0x01, 0x81,0x06,           # гориз. прокрутка
    0xC0, 0xC0]
def cfg(hs):
    ival = 4 if hs else 1          # HS: 2^(4-1) микрокадров = 1 мс; FS: 1 мс
    b = [9,2,0,0, 2,1,0, 0xC0, 25]  # 2 интерфейса, самопитание, 50 мА
    b += [9,4, 0,0,1, 3,1,1, 0]     # IF0: HID, boot, клавиатура
    b += [9,0x21, 0x11,0x01, 0,1, 0x22] + w16(len(kbd_rpt))
    b += [7,5, 0x81, 3] + w16(8) + [ival]
    b += [9,4, 1,0,1, 3,0,0, 0]     # IF1: HID, мышь (абсолютная, без boot)
    b += [9,0x21, 0x11,0x01, 0,1, 0x22] + w16(len(mouse_rpt))
    b += [7,5, 0x82, 3] + w16(8) + [ival]
    b[2:4] = w16(len(b))
    return b
dev  = [18,1, 0x00,0x02, 0,0,0, 64] + w16(VID) + w16(PID) + w16(BCD) + [1,2,0, 1]
qual = [10,6, 0x00,0x02, 0,0,0, 64, 1, 0]
rom, addr = [], {}
def put(name, b, pad=0):
    addr[name] = (len(rom), len(b)); rom.extend(b + [0]*pad)
put('dev', dev, 2); put('qual', qual, 2); put('fscfg', cfg(False)); put('hscfg', cfg(True)); put('oscfg', [0])
put('lang', [4,3,0x09,0x04]); put('vendor', s('PRIMER KVM')); put('product', s('PRIMER KVM Keyboard/Mouse'))
put('kbdrpt', kbd_rpt); put('mouserpt', mouse_rpt)
out = ['// Generated by scripts/usbdesc.py (python scripts/usbdesc.py). Do not edit.',
       '// USB descriptor ROM for usb_hid.sv (Gowin USB 2.0 Device Controller, IPUG927 3.6): device, qualifier,',
       '// FS/HS configuration (IF0 boot keyboard, EP1 IN interrupt 8 B; IF1 absolute mouse, EP2 IN interrupt 8 B;',
       '// 1 ms polling, self powered), language/vendor/product strings, HID report descriptors.',
       '// Keyboard report (8 B): modifiers, 0, 6 key usages. Mouse report (7 B): buttons[4:0], X u16, Y u16',
       '// (0..32767, absolute), wheel i8, horizontal pan i8.',
       'module usb_desc_rom (',
       '    input  logic [15:0] addr,',
       '    output logic [7:0]  data']
for k,(a,l) in addr.items():
    out[-1] += ','
    out.append(f'    output logic [15:0] {k}_addr, {k}_len')
out.append(');')
for k,(a,l) in addr.items():
    out.append(f"    assign {k}_addr = 16'd{a};  assign {k}_len = 16'd{l};")
out.append('    always_comb begin')
out.append('        case (addr)')
for i,v in enumerate(rom):
    if v: out.append(f"            16'd{i}: data = 8'h{v:02X};")
out.append("            default: data = 8'h00;")
out.append('        endcase')
out.append('    end')
out.append('endmodule')
here = os.path.dirname(os.path.abspath(__file__))
dst = os.path.join(here, '..', 'fpga', 'rtl', 'usb_desc_rom.sv')
open(dst, 'w', newline='\r\n', encoding='utf-8').write('\n'.join(out) + '\n')
print('usb_desc_rom.sv:', len(rom), 'bytes')
