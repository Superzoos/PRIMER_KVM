function MHz ([decimal]$hz) { return ($hz / 1000000).ToString($inv) }

# ---------- rPLL ----------
function Find-Pll ([decimal]$fout, [string]$what) {
    $best = $null
    foreach ($id in 1..64) {
        $pfd = $fin / $id
        if ($pfd -lt 3000000 -or $pfd -gt 500000000) { continue }
        foreach ($fb in 1..64) {
            if ($fin * $fb -ne $fout * $id) { continue }
            foreach ($od in @(2, 4, 8, 16, 32, 48, 64, 80, 96, 112, 128)) {
                $vco = $fout * $od
                if ($vco -lt 500000000 -or $vco -gt 1250000000) { continue }
                $c = @{ ID = $id; FB = $fb; OD = $od; PFD = $pfd; VCO = $vco; F = $fout }
                if (-not $best -or $c.PFD -gt $best.PFD -or
                    ($c.PFD -eq $best.PFD -and [math]::Abs($c.VCO - 800000000) -lt [math]::Abs($best.VCO - 800000000))) { $best = $c }
            }
        }
    }
    if (-not $best) { Die ("PLL ({0}): из {1} МГц нельзя точно получить {2} МГц в допустимых диапазонах" -f $what, (MHz $fin), (MHz $fout)) }
    return $best
}

function Write-Pll ([string]$module, $p) {
    Write-IfChanged (Join-Path $fpga "ip\$module\$module.v") @"
// $hdr
// rPLL: $(MHz $fin) MHz / $($p.ID) * $($p.FB) = $(MHz $p.F) MHz, PFD $(MHz $p.PFD) MHz, VCO $(MHz $p.VCO) MHz (ODIV $($p.OD))
module $module (clkout, lock, reset, clkin);
output clkout;
output lock;
input reset;
input clkin;
wire clkoutp_o;
wire clkoutd_o;
wire clkoutd3_o;
wire gw_gnd;
assign gw_gnd = 1'b0;
rPLL rpll_inst (
    .CLKOUT(clkout),
    .LOCK(lock),
    .CLKOUTP(clkoutp_o),
    .CLKOUTD(clkoutd_o),
    .CLKOUTD3(clkoutd3_o),
    .RESET(reset),
    .RESET_P(gw_gnd),
    .CLKIN(clkin),
    .CLKFB(gw_gnd),
    .FBDSEL({gw_gnd,gw_gnd,gw_gnd,gw_gnd,gw_gnd,gw_gnd}),
    .IDSEL({gw_gnd,gw_gnd,gw_gnd,gw_gnd,gw_gnd,gw_gnd}),
    .ODSEL({gw_gnd,gw_gnd,gw_gnd,gw_gnd,gw_gnd,gw_gnd}),
    .PSDA({gw_gnd,gw_gnd,gw_gnd,gw_gnd}),
    .DUTYDA({gw_gnd,gw_gnd,gw_gnd,gw_gnd}),
    .FDLY({gw_gnd,gw_gnd,gw_gnd,gw_gnd})
);
defparam rpll_inst.FCLKIN = "$(MHz $fin)";
defparam rpll_inst.DYN_IDIV_SEL = "false";
defparam rpll_inst.IDIV_SEL = $($p.ID - 1);
defparam rpll_inst.DYN_FBDIV_SEL = "false";
defparam rpll_inst.FBDIV_SEL = $($p.FB - 1);
defparam rpll_inst.DYN_ODIV_SEL = "false";
defparam rpll_inst.ODIV_SEL = $($p.OD);
defparam rpll_inst.PSDA_SEL = "0000";
defparam rpll_inst.DYN_DA_EN = "true";
defparam rpll_inst.DUTYDA_SEL = "1000";
defparam rpll_inst.CLKOUT_FT_DIR = 1'b1;
defparam rpll_inst.CLKOUTP_FT_DIR = 1'b1;
defparam rpll_inst.CLKOUT_DLY_STEP = 0;
defparam rpll_inst.CLKOUTP_DLY_STEP = 0;
