function Copy-IpDir ([string]$src, [string]$dst, [string[]]$skip = @()) {
    New-Item -ItemType Directory -Path $dst -Force | Out-Null
    foreach ($f in Get-ChildItem -LiteralPath $src -File | Where-Object { $_.Name -notin $skip }) {
        $d = Join-Path $dst $f.Name
        if (-not (Test-Path -LiteralPath $d) -or (Get-FileHash -LiteralPath $d).Hash -ne (Get-FileHash -LiteralPath $f.FullName).Hash) {
            Copy-Item -LiteralPath $f.FullName -Destination $d -Force
        }
    }
}
