Write-IfChanged (Join-Path $usbDir 'usb_dev_all.v') @"
// $hdr
// Compiles the encrypted module usb_device_controller (USB device core) together with its settings (see ip-gen.ps1).
``include "static_macro_define.v"
``include "usb_device_controller_define.v"
