# ---------- Временные ограничения ----------
# Запас по частоте: все такты задаются в (1 + TIMING_MARGIN_PCT/100) раз быстрее настоящих, поэтому
# отсутствие нарушений setup в отчёте P&R означает запас не меньше заданного (synth.ps1 это проверяет).
$mk   = 1 + [decimal](Get-Cfg $cfg 'TIMING_MARGIN_PCT') / 100
$feth = [decimal]50000000
$fusb = [decimal]60000000
function Ns ([decimal]$hz, [decimal]$k) { return ([math]::Round(1000000000 / ($hz * $mk) * $k, 3)).ToString($inv) }
# ULPI I/O (USB3317 rev C, табл. 4.3): запас - в наносекундах ($ioM), а не в процентах частоты (задержки выводов от
# частоты не зависят). Период usb_clk в SDC короче реального на $dT, поэтому max-задержки уменьшены на $dT:
# проверка setup идёт против реального периода 60 МГц с запасом $ioM; min-задержки строже на $ioH (hold).
$ioM = [decimal]1.0
$ioH = [decimal]0.5
$dT  = [decimal]1000000000 / $fusb - [decimal]1000000000 / ($fusb * $mk)
function IoNs ([decimal]$v) { return ([math]::Round($v, 3)).ToString($inv) }
Write-IfChanged (Join-Path $fpga 'constraints\kvm.sdc') @"
// $hdr
// All periods are the real ones divided by $($mk.ToString($inv)) (TIMING_MARGIN_PCT): a clean P&R means at least that margin.
create_clock -name clk_27m -period $(Ns $fin 1) -waveform {0 $(Ns $fin 0.5)} [get_ports {clk_27m}]
create_clock -name clk_sys -period $(Ns $fcpu 1) -waveform {0 $(Ns $fcpu 0.5)} [get_pins {u_clk_rst/u_pll/rpll_inst/CLKOUT}]
create_clock -name tmds_clk -period $(Ns $fpix 1) -waveform {0 $(Ns $fpix 0.5)} [get_ports {tmds_clk_p}]
create_clock -name eth_ref -period $(Ns $feth 1) -waveform {0 $(Ns $feth 0.5)} [get_ports {eth_ref_clk}]
// MII 25 MHz: refclk / 2 on a register inside MII to RMII (IPUG1195 3.2); net = tx_mac_clk of the MAC
create_generated_clock -name eth_mii -source [get_ports {eth_ref_clk}] -divide_by 2 [get_nets {u_eth_sys/tx_clk}]
// Gowin starts eth_mii at the divider output with zero delay; the real path is longer:
// input buffer (1.392 ns, fast model) + route to divider + divider register (SUG940 5.2.3).
// early 1.0 ns < input buffer alone (safe for hold eth_mii->eth_ref); late 5.0 ns - upper estimate.
set_clock_latency -source -early 1.0 [get_clocks {eth_mii}]
set_clock_latency -source -late 5.0 [get_clocks {eth_mii}]
// DDR3: memory clock from rPLL; user clock = IP clk_out = output of CLKDIV /4 inside the IP. Declared as
// generated from the PLL (as in Sipeed Cam2HDMI): timing reports then show the PLL site in ddr_clk clock paths.
create_clock -name ddr_mem -period $(Ns $fddr 1) -waveform {0 $(Ns $fddr 0.5)} [get_pins {u_pll_ddr/rpll_inst/CLKOUT}]
create_generated_clock -name ddr_clk -source [get_pins {u_pll_ddr/rpll_inst/CLKOUT}] -master_clock ddr_mem -divide_by 4 [get_pins {u_ddr3/gw3_top/u_ddr_phy_top/fclkdiv/CLKOUT}]
// HDMI: pixel clock = IP DVI RX O_rgb_clk (rPLL x5 -> CLKDIV /5), top-level net pix_clk (IPUG938 3.5)
create_clock -name pix_clk -period $(Ns $fpix 1) -waveform {0 $(Ns $fpix 0.5)} [get_nets {pix_clk}]
// Inside the IP: x5 serial clocks of its rPLL (CLKOUT, CLKOUTP) are declared explicitly (names of the clocks
// Gowin derives itself cannot be used in SDC, TA2004). TMDS clock, x5 clocks and pixel clock are exclusive
// groups, as IPUG938 3.5 recommends (the IP aligns the IDES10 reset itself).
create_generated_clock -name rx_x5 -source [get_ports {tmds_clk_p}] -multiply_by 5 [get_pins {u_dvi_rx/dvi2rgb_inst/rPLL_inst/CLKOUT}]
create_generated_clock -name rx_x5p -source [get_ports {tmds_clk_p}] -multiply_by 5 [get_pins {u_dvi_rx/dvi2rgb_inst/rPLL_inst/CLKOUTP}]
set_clock_groups -exclusive -group [get_clocks {tmds_clk}] -group [get_clocks {rx_x5 rx_x5p}] -group [get_clocks {pix_clk}]
// USB: ULPI CLKOUT of USB3317, 60 MHz (as in Sipeed usb_cdc example)
create_clock -name usb_clk -period $(Ns $fusb 1) -waveform {0 $(Ns $fusb 0.5)} [get_ports {ulpi_clk}]
// ULPI I/O timing of USB3317 rev C (table 4.3), relative to the rising edge of CLKOUT at the PHY:
// PHY outputs (DIR, NXT, DATA) change 1.5..3.5 ns after the edge; PHY inputs (STP, DATA) need setup 5.0 ns, hold 0.
// CLKOUT reaches the FPGA clock net through generic routing (PR1014), so its delay is large: without these
// constraints P&R does not check the I/O paths at all (input hold, output setup).
// Margin here is $(IoNs $ioM) ns, not a percentage: max delays are reduced by $(IoNs $dT) ns (real period - period above),
// so setup is checked against the real 60 MHz period; input min delay is stricter by $(IoNs $ioH) ns (hold).
set_input_delay -clock usb_clk $(IoNs (3.5 + $ioM - $dT)) -max [get_ports {ulpi_dir ulpi_nxt ulpi_data[*]}]
set_input_delay -clock usb_clk $(IoNs (1.5 - $ioH)) -min [get_ports {ulpi_dir ulpi_nxt ulpi_data[*]}]
set_output_delay -clock usb_clk $(IoNs (5.0 + $ioM - $dT)) -max [get_ports {ulpi_stp ulpi_data[*]}]
set_output_delay -clock usb_clk 0.0 -min [get_ports {ulpi_stp ulpi_data[*]}]
// DIR -> output enable of DATA is combinational (link releases the bus in the turnaround cycle, the PHY does not
// read DATA in it - USB3317 6.1.1); its real limit is one clock, not "input + output delay" of the same edge.
set_false_path -from [get_ports {ulpi_dir}] -to [get_ports {ulpi_data[*]}]
set_clock_groups -asynchronous -group [get_clocks {clk_27m}] -group [get_clocks {clk_sys}] -group [get_clocks {tmds_clk}] -group [get_clocks {eth_ref eth_mii}] -group [get_clocks {ddr_mem}] -group [get_clocks {ddr_clk}] -group [get_clocks {pix_clk}] -group [get_clocks {usb_clk}]
// Worst paths of each working clock in the timing report (fpga\impl\pnr\*.tr), to see where the margin goes
report_timing -setup -from_clock [get_clocks {clk_sys}] -to_clock [get_clocks {clk_sys}] -max_paths 10 -max_common_paths 1
report_timing -setup -from_clock [get_clocks {ddr_clk}] -to_clock [get_clocks {ddr_clk}] -max_paths 10 -max_common_paths 1
report_timing -setup -from_clock [get_clocks {pix_clk}] -to_clock [get_clocks {pix_clk}] -max_paths 10 -max_common_paths 1
report_timing -setup -from_clock [get_clocks {usb_clk}] -to_clock [get_clocks {usb_clk}] -max_paths 10 -max_common_paths 1
report_timing -hold -from_clock [get_clocks {usb_clk}] -to_clock [get_clocks {usb_clk}] -max_paths 10 -max_common_paths 1
"@ -Quiet

Ok ('IP: ядро {0} МГц, DDR3 {1} МГц, HDMI {2} МГц, фаза {3}' -f (MHz $fcpu), (MHz $fddr), (MHz $fpix), $(if ($dviAuto) { 'auto' } else { $dviPhN }))
exit 0
