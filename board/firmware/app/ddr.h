/* ddr.h - запуск и проверка DDR3. */
#ifndef DDR_H
#define DDR_H

#include <stdint.h>

/* Дождаться калибровки (до 3 с; в UART - состояние PLL, сброса и такта IP) и проверить память (адресные линии, запись байтами, 256 КБ данных).
 * Итог - в UART. Возвращает объём в байтах или 0 при ошибке. Портит данные по адресам
 * 2^k, 0x100..0x11F и 64 МБ..+256 КБ. */
uint32_t ddr_init(void);
/* Если калибровка завершилась позже ddr_init(), - проверить память (один раз).
 * now_ms - время от старта для сообщения. Возвращает объём или 0. */
uint32_t ddr_poll(uint32_t now_ms);

#endif /* DDR_H */
